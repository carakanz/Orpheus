print("## 10. Сеть: засчитан ли уворот, нажатый вовремя на своём экране\n")
random.seed(28)


def dodge_ok(delta, hold):
    lat = A.one_way + random.uniform(-A.jitter, A.jitter)
    if random.random() < 0.01:   # первый пакет потерян, нажатие едет в следующем (15.4)
        lat += 1 / 60
    arrive = -delta + lat         # удар — в момент 0 по часам сервера
    return arrive <= hold


rows = []
for lo, hi in ((0, 17), (17, 33), (33, 50), (50, 67), (67, 100), (100, 200)):
    ok_a = ok_b = 0
    n = 4000
    for _ in range(n):
        dlt = random.uniform(lo, hi) / 1000
        ok_a += dodge_ok(dlt, 0.0)
        ok_b += dodge_ok(dlt, A.hold)
    rows.append([f"{lo}–{hi} мс", pct(ok_a / n), pct(ok_b / n)])
table(["Нажат до касания на экране", "Сервер решает в момент удара", f"Сервер ждёт ввод до {A.hold * 1000:.0f} мс"], rows)
