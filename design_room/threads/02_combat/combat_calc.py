def spam(cd=CD, refund=0, n_max=12, dt=0.0005):
    """Жмём уворот при первой возможности. Возвращает [(время нажатия, выносливость после)]."""
    t, st, last_spend, ready = 0.0, float(MAXS), -10.0, 0.0
    out = []
    while t < 30 and len(out) < n_max:
        if t >= ready - 1e-9 and st >= COST - 1e-9:
            st -= COST
            last_spend = t
            if refund:
                st = min(MAXS, st + refund)
            out.append((round(t, 3), st))
            ready = t + DASH + cd
        if t - last_spend >= DELAY and st < MAXS:
            st = min(MAXS, st + REGEN * dt)
        t += dt
    return out


