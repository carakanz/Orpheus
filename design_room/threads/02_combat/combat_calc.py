def melee_cycle(mults, wind, act, rec, base):
    """Серия: последний удар с отходом x1,5 (02 3.2). Без серии — без x1,5 (так в 02 посчитан кинжал)."""
    n = len(mults)
    one = wind + act + rec
    if n == 1:
        return base * mults[0] / one
    t = one * (n - 1) + wind + act + rec * 1.5
    return base * sum(mults) / t


