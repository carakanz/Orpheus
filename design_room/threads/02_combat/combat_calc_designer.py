def hero_dps(act, model):
    if model == "00":          # шкала 00: оружие 1-го яруса, 1,5 удара/с, без способностей
        return 1.5 * B[act]
    return 1.5 * B[act] * TIER2 * ABIL[act]   # 02 10.1: ярус 2, способности


def k_targets(n):
    return 1 + (n - 1) // 3


def boss_time(act, n, c=0, w=0.1, a=1.0, model="02", u_free=None, u_comp=None, c_dmg=True):
    u_free = A.u_free if u_free is None else u_free
    u_comp = A.u_comp if u_comp is None else u_comp
    neff = n + w * c
    hp = BOSS_HP[act] * (1 + a * (neff - 1))
    d = hero_dps(act, model)
    k = min(n, k_targets(n))
    dps = d * (k * A.u_target + (n - k) * u_free)
    if c_dmg:
        dps += c * 0.45 * B[act] * u_comp
    return hp / dps


