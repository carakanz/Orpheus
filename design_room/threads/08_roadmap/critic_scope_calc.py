def names(seg):
    res = []
    for part in split_top(seg):
        p = part.strip()
        p = re.sub(r"^(\+\s*|ночь:\s*|Ночь:\s*)+", "", p)
        p = re.split(r"[\(\[]", p)[0].strip(" .:+")
        p = re.sub(r"^(ночь:\s*)", "", p).strip()
        if not p or len(p) > 40:
            continue
        p = p.lower()
        if p in SKIP:
            continue
        res.append(ALIAS.get(p, p))
    return res


def tri(t):
    return random.triangular(t[0], t[2], t[1])


