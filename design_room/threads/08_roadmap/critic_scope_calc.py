def sim(act, n_mb, n_biomes, n_ds, n_dsep, art_scale=1.0, split=False, runs=N_RUNS, es=1.0, ns=1.0):
    """es — доля видов врагов и их версий; ns — множитель всех норм потоков (чувствительность)."""
    comp, one = milestone(act, n_mb, n_biomes, n_ds, n_dsep)
    comp = {s: [(k, q * es if k in ("враг", "версия врага") else q) for k, q in v] for s, v in comp.items()}
    assets = art_assets(act, n_mb, art_scale)
    out, loads = [], {"Я": [], "М": [], "К": [], "Б": []}
    MOVE = {"Я": ("босс", "мини-босс", "хранитель", "способность"),
            "М": ("биом", "поздний биом", "данж-участок", "данж отдельный", "логово")}
    for _ in range(runs):
        st, b = {}, 0.0
        for s in comp:
            tot = sum(tri(t) for t in one[s])
            for k, q in comp[s]:
                if q <= 0:
                    continue
                x = tri(N[k]) * q
                tot += x
                if split and s == split and k in MOVE[split]:
                    b += x
            st[s] = tot * ns
        st["К"] += tri(N["вклейка 100 ассетов"]) * assets / 100 * ns
        lim, eff = tri(LIMIT), tri(EFF)
        if split:
            st[split] -= b * ns
            st["Б"] = b * ns
            lim, eff = lim * 1.05, eff * 0.95
        for s in st:
            loads[s].append(st[s])
        code = max(max(st.values()) * REB, sum(st.values()) / len(st)) * lim / eff
        art =assets / tri(ART_RATE) * lim - OVERLAP[act]
        out.append(max(code, art) + tri(FIXED) + 1.0)
    out.sort()
    q = (out[int(runs * 0.1)], out[runs // 2], out[int(runs * 0.9)])
    return q, {s: (statistics.median(v) if v else 0) for s, v in loads.items()}, assets


