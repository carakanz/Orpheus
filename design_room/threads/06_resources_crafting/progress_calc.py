def expand(item, n, acc):
    """развернуть n штук item до сырья; acc[сырьё] += кол-во"""
    if item not in R:
        acc[item] = acc.get(item, 0) + n
        return
    station, inputs, out = R[item]
    crafts = n / out
    for k, q in inputs.items():
        expand(k, q * crafts, acc)


def raw_of(kit):
    acc = {}
    for item, n in kit:
        expand(item, n, acc)
    # смола идёт с деревьями: 1 смола на дерево (3 древесины); лишних деревьев не нужно, если смолы ≤ древесина/3
    return acc


def gather_minutes(acc, pick, axe):
    """минуты добычи на сырьё; возвращает (итого, разбивка, нехватка инструмента)"""
    out, total, blocked = {}, 0.0, []
    wood = acc.get("древесина", 0)
    resin = acc.get("смола", 0)
    extra_trees_wood = max(0.0, resin * 3 - wood)  # если смолы больше, чем даёт рубка
    for res, q in acc.items():
        if res in TROPHY or res == "смола":
            continue
        qq = q + (extra_trees_wood if res == "древесина" else 0)
        r = rate(res, pick, axe)
        if r <= 0:
            blocked.append(res)
            continue
        m = qq / r
        out[res] = m
        total += m
    return total, out, blocked


