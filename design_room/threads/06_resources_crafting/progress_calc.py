def walk_time(density):
    if density is None:
        return FACE_WALK
    return NEAR * math.sqrt(1000.0 / density) * ROUTE / V


def rate(res, pick, axe):
    """ед./мин при силе кирки pick и топора axe (0 — нельзя)."""
    if res in SPECIAL_RATE:
        return SPECIAL_RATE[res]
    where, tool, hard, t, y, dens = RAW[res]
    if tool == "hand":
        speed = 1.0
    else:
        power = pick if tool == "pick" else axe
        if power < hard:
            return 0.0
        speed = 2 ** min(2, power - hard)
    per_obj = (t / speed + walk_time(dens)) * INTERF
    return 60.0 * y / per_obj


