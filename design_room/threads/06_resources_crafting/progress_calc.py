    act_total = {}
    rows = []
    for act, name, dur, pick, axe, kit in STEPS:
        acc = raw_of(kit)
        total, parts, blocked = gather_minutes(acc, pick, axe)
        act_total.setdefault(act, 0.0)
        act_total[act] += total
        top = sorted(parts.items(), key=lambda kv: -kv[1])[:4]
        top_s = "; ".join(f"{k} {f(v)}" for k, v in top)
        trophies = {k: v for k, v in acc.items() if k in TROPHY}
        tro_s = ", ".join(f"{k} {f(v, 0)}" for k, v in trophies.items()) if trophies else "—"
