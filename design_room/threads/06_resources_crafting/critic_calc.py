def crit_obj(res, pick, axe, route_mult=1.0):
    """секунды на объект (без помех) и выход; None — нет инструмента"""
    where, tool, hard, t, y, dens = pc.RAW[res]
    if tool == "hand":
        speed = 1.0
    else:
        power = pick if tool == "pick" else axe
        if power < hard:
            return None
        speed = 2 ** min(2, power - hard)
    t_obj = t / speed
    if dens is None:
        return t_obj + pc.FACE_WALK, y
    b = WHERE.get(res, "луга")
    k, r = BIOME[b]
    rho = DENS_CRIT.get(res, dens) / 1000.0
    if res == "глина":
        path = 1.0 / (3 * rho)                       # полоса берега шириной 3 т
    else:
        vis = 11.0 if res in GLOW else r
        path = max(0.7124 / math.sqrt(rho),          # обход точек по ближайшим (задача коммивояжёра)
                   1.0 / (2 * vis * rho))            # поиск полосой видимости
    walk = path * k * route_mult / V
    tunnel = (1.0 / 2 ** min(2, max(pick, 1) - 1)) if (b in EMBED and tool == "pick") else 0.0
    return t_obj + walk + tunnel, y


def crit_rate(res, pick, axe, route_mult=1.0, interf=1.25):
    if res in SPECIAL_CRIT:
        return SPECIAL_CRIT[res]
    r = crit_obj(res, pick, axe, route_mult)
    if r is None:
        return 0.0
    per, y = r
    return 60.0 * y / (per * interf)


def gather_crit(acc, pick, axe, route_mult=1.0, interf=1.25):
    total, parts = 0.0, {}
    wood = acc.get("древесина", 0)
    resin = acc.get("смола", 0)
    extra = max(0.0, resin * 3 - wood)
    for res, q in acc.items():
        if res in pc.TROPHY or res in ("смола", "мясо", "шкура"):
            continue
        qq = q + (extra if res == "древесина" else 0)
        r = crit_rate(res, pick, axe, route_mult, interf)
        if r <= 0:
            parts[res] = float("nan")
            continue
        m = qq / r
        parts[res] = m
        total += m
    hunt = max(acc.get("мясо", 0) / SPECIAL_CRIT["мясо"], acc.get("шкура", 0) / SPECIAL_CRIT["шкура"])
    if hunt:
        parts["охота"] = hunt
        total += hunt
    return total, parts


