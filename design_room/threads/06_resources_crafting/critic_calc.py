B = {"I": 10, "II": 30, "III": 90}
TIER = {1: 1.0, 2: 1.5, 3: 1.8}
AB = {"I": 0.30, "II": 0.50, "III": 0.70}
PET = {"I": 0.0, "II": 0.30, "III": 0.35}      # питомец / боевой дрон, B в секунду (06, 4.10)
PET_UP = 0.7                                   # доля боя, когда питомец жив и бьёт (прикидка)
COMP = 0.45                                    # спутник, B в секунду (02, 12.3)
COMP_UP = 0.7
SCALE = {"I": (3, 5), "II": (4, 6), "III": (5, 8)}


def hero_dps(ep, tier):
    return 1.5 * B[ep] * TIER[tier] * (1 + AB[ep]) * 0.5


def fight(hp, ep, tier, pet=False, comps=0):
    dps = hero_dps(ep, tier) + (PET[ep] * B[ep] * PET_UP if pet else 0) + comps * COMP * B[ep] * COMP_UP
    hp_eff = hp * (1 + 0.1 * comps)
    return hp_eff / dps / 60


