        lam = dens * 1.024
        target = max(1, int(lam / 2 + 0.5))
        add = 0.0
        for k in range(0, target):
            add += (target - k) * math.exp(-lam) * lam ** k / math.factorial(k)
        print(f"  - {name}: в среднем {f(lam, 2)} на чанк, цель {target} → +{pct(add / lam)} руды на нетронутых чанках.")
