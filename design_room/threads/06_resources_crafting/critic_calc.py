def trip_minutes(step_no, mult=1.0):
    total = 0.0
    saved = 0.0
    for name, d, shared in TRIPS.get(step_no, []):
        one = d * DETOUR / V / 60 * (1 - shared)
        if step_no in WALK_BACK_STEPS:
            total += 2 * one
        else:
            total += one + CLEW
            saved += one - CLEW
    return total * mult, saved * mult


