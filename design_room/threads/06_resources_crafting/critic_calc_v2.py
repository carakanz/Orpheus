def fn(n):
    return 1 + 0.5 * (n - 1)


def run_group():
    print("## 5. Группа: личный дроп с поправкой 1 / f(n)\n")
    print("`02` 8.5: группе с пересекающимися окрестностями появляется f(n) = 1 + 0,5 (n − 1) врагов на одного. Правило [3]: "
          "участник — каждый на ногах в 40 т от убитого врага, вводивший команды последние 120 с, или нанёсший ему урон за 10 с. "
          "Каждый участник бросает **свой** дроп: у появившихся врагов шанс каждой строки таблицы × 1 / f(n), у расставленных "
          "(лагеря, крыши, данжи) — без поправки. Оболы — так же. Свой дроп видит и поднимает только владелец.\n")
    print("| n | f(n) | Жребий [1]: появившиеся | Жребий [1]: расставленные | Личный дроп [3]: появившиеся | Личный дроп [3]: расставленные |")
    print("|---|---|---|---|---|---|")
    for n in (1, 2, 4, 8, 16):
        F = fn(n)
        old_sp, old_pl = F / n, 1 / n
        new_sp = F * (1 / F)        # врагов ×f(n), шанс ×1/f(n)
        new_pl = 1.0                # врагов столько же, шанс ×1, свой бросок у каждого
        print(f"| {n} | {f(F, 1)} | {pct(old_sp)} | {pct(old_pl)} | {pct(new_sp)} | {pct(new_pl)} |")
    print()
    print("На человека выходит как соло при любом n: «вместе» не хуже, чем «одному» (С5), и не лучше — копий восьмерым нет. "
          "Гонки за касанием нет: участник — по присутствию, а не по урону.\n")
    # проверка приёмки: четверо бьют 400 волков вместе (появившиеся), мясо 100 % × 1/f(4) = 0,4 у каждого
    rng = random.Random(29)
    trials = 20000
    c = 1 / fn(4)
    ok = 0
    for _ in range(trials):
        good = True
        for _ in range(4):
            k = sum(1 for _ in range(400) if rng.random() < c)
            if not (130 <= k <= 190):
                good = False
        ok += good
    print(f"Приёмка 9.7.1: четверо вместе убили 400 волков — мясо у каждого (шанс 0,4, ожидание 160) в 130–190: "
          f"проходит в {pct(ok / trials)} прогонов ({trials} моделирований).\n")


