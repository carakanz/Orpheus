B = {"I": 10, "II": 30, "III": 90}
TIER = {1: 1.0, 2: 1.5, 3: 1.8}
AB = {"I": 0.30, "II": 0.50, "III": 0.70}
PET_O = 0.08                                   # питомец и дрон [3]: 0,08 О/с — 2/3 волка-тени (03 8.1: 0,12 О/с)
WOLF_O = 0.12
PET_UP = 0.7
COMP = 0.45
COMP_UP = 0.7
SCALE = {"I": (3, 5), "II": (4, 6), "III": (5, 8)}


def hero_dps(ep, tier):
    return 1.5 * B[ep] * TIER[tier] * (1 + AB[ep]) * 0.5


def pet_dps(ep, tier):
    return PET_O * B[ep] * TIER[tier] * PET_UP if ep != "I" else 0.0


def fight(hp, ep, tier, pet=False, comps=0):
    dps = hero_dps(ep, tier) + (pet_dps(ep, tier) if pet else 0) + comps * COMP * B[ep] * COMP_UP
    return hp * (1 + 0.1 * comps) / dps / 60


