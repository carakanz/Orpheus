#!/usr/bin/env python3
"""Расчёты Критика по шкалам docs/00_vision.md (смена 28.10).

Запуск:
    python C:\\Users\\carak\\source\\Orpheus\\design_room\\threads\\00_vision\\scales.py
    python scales.py --msps1 <M выборок/с, 1 поток> --mspsp <M выборок/с, все потоки>   # числа из noise_bench

Печатает таблицы в Markdown; копия вывода лежит рядом в scales.md.
Скорость шума по умолчанию — измеренная noise_bench на машине Критика (см. noise_bench/Program.cs и scales.md).
Все модели простые и помечены как прикидки: цель — порядок величин, а не точность.
"""
import argparse
import math
import sys

sys.stdout.reconfigure(encoding="utf-8")

P = argparse.ArgumentParser()
P.add_argument("--msps1", type=float, default=57.9, help="M выборок шума/с, один поток (noise_bench, 28.10)")
P.add_argument("--mspsp", type=float, default=183.4, help="M выборок шума/с, все потоки (noise_bench, 28.10, 16 логических ядер)")
P.add_argument("--samples", type=int, default=18, help="выборок шума на тайл (высота 5, влажность 3, температура 3, пещеры 3, руда 2, детали 2)")
P.add_argument("--passes", type=int, default=4, help="проходов постобработки по всему миру (биомы, связность, залежи, данжи)")
P.add_argument("--pass-mtps", type=float, default=40.0, help="M тайлов/с на один проход постобработки, один поток")
A = P.parse_args()

SCREEN_W, SCREEN_H = 40, 22.5   # тайлов на экране при 1080p и 48 px/тайл (зум ×0,75 от исходника 64 px)
RUN = 6.0                       # тайлов/с, бег
DETOUR = 1.5                    # множитель за обход гор и воды (из документа)
PLAYERS = 8
CHUNK = 32
DAY = (12, 1, 6, 1)             # день, сумерки, ночь, рассвет — минут


def table(head, rows):
    print("| " + " | ".join(head) + " |")
    print("|" + "---|" * len(head))
    for r in rows:
        print("| " + " | ".join(str(c) for c in r) + " |")
    print()


def f(x, d=1):
    return f"{x:,.{d}f}".replace(",", " ")


print("# Расчёты по шкалам 00_vision (Критик, 28.10)\n")
print(f"Параметры: экран {SCREEN_W}×{SCREEN_H} тайлов, бег {RUN} т/с, обход ×{DETOUR}, игроков {PLAYERS}, "
      f"шум {A.msps1} / {A.mspsp} M выборок/с (1 поток / все), {A.samples} выборок на тайл, "
      f"{A.passes} прохода по {A.pass_mtps} M тайлов/с.\n")

# 1. Размер мира ---------------------------------------------------------------
print("## 1. Размер мира\n")
rows = []
for n in (1024, 2048, 4096, 8192):
    tiles = n * n
    screens = tiles / (SCREEN_W * SCREEN_H)
    loop = n / RUN
    reveal_h = tiles / (RUN * SCREEN_H) / 3600           # бежать полосой в высоту экрана, пока не увидишь всё
    gen1 = tiles * A.samples / (A.msps1 * 1e6) + A.passes * tiles / (A.pass_mtps * 1e6)
    genp = tiles * A.samples / (A.mspsp * 1e6) + A.passes * tiles / (A.pass_mtps * 1e6)
    rows.append([
        f"{n}²", f(tiles / 1e6) + " M", (n // CHUNK) ** 2, f(screens, 0),
        f"{loop / 60:.1f} / {loop * DETOUR / 60:.1f}",
        f(tiles / PLAYERS / 1e6) + " M / " + f(screens / PLAYERS, 0),
        f"{reveal_h:.1f} / {reveal_h / PLAYERS:.1f}",
        f"{tiles * 4 / 1e6:.0f} / {tiles * 8 / 1e6:.0f} / {tiles * 16 / 1e6:.0f}",
        f"{gen1:.1f} / {genp:.1f}",
    ])
table(["Мир", "Тайлов", "Чанков", "Экранов", "Обход по экватору, мин (прямо / ×1,5)",
       "На игрока из 8: тайлов / экранов", "Увидеть всё, ч (соло / ввосьмером)",
       "ОЗУ мира, МБ (4 / 8 / 16 Б на тайл)", "Генерация, с (1 поток / все)"], rows)

print("Сравнение: Terraria, большой мир — 8400 × 2400 = 20,2 M тайлов, из них поверхность ≈ 8400 × 300 ≈ 2,5 M; "
      "экран при 1080p и 16 px — 120 × 67,5 тайла; ширина мира — 70 экранов. "
      "У нас 4096² — 102 экрана в ширину и 182 в высоту, вся площадь — поверхность.\n")

# 1б. Средний размер биома -------------------------------------------------------
print("## 1б. Если каждый биом — одна связная область (как сейчас в глоссарии)\n")
rows = []
for n in (2048, 4096):
    for k in (4, 11, 14):
        side = math.sqrt(n * n / k)
        rows.append([f"{n}²", k, f(side, 0), f"{side / RUN / 60:.1f}", f(side / SCREEN_W, 0)])
table(["Мир", "Биомов", "Сторона биома, тайлов", "Пересечь биом, мин", "Экранов в ширину"], rows)
print("Terraria: самый большой биом (джунгли на большом мире) ≈ 1000 тайлов ≈ 8 экранов в ширину, лес ≈ 2–3 экрана.\n")

# 1в. Сколько мира видит соло-игрок за акт I ---------------------------------------
print("## 1в. Разведка за акт I соло (4096²)\n")
rows = []
for hours in (10, 12):
    for share in (0.25, 0.33, 0.5):
        seen = hours * share * 3600 * RUN * SCREEN_H
        rows.append([hours, f"{share:.0%}", f(seen / 1e6) + " M", f"{seen / 4096**2:.0%}"])
table(["Акт I, ч", "Доля времени в беге", "Увидено тайлов", "Доля мира"], rows)

# 1г. Радиус от базы ------------------------------------------------------------------
print("## 1г. Что в радиусе от базы (4096²)\n")
rows = []
for minutes in (1, 3, 5, 10):
    r = minutes * 60 * RUN
    area = min(math.pi * r * r, 4096 ** 2)
    rows.append([minutes, f(r, 0), f(r / SCREEN_W, 0), f"{area / 4096**2:.0%}"])
table(["Мин бега от базы", "Радиус, тайлов", "Экранов", "Доля мира в круге"], rows)
print("Световой день 12 мин: туда 6 мин — 2 160 тайлов — и это уже больше половины экватора (2 048). "
      "Дальше базы, чем полдня пути, на торе не уйти вообще.\n")

# 2. Сутки и акт ------------------------------------------------------------------------
print("## 2. Сутки 20 мин и длительность акта\n")
day_len = sum(DAY)
rows = []
for hours in (10, 12, 15):
    days = hours * 60 / day_len
    rows.append([hours, f"{days:.0f}", f"{days * DAY[2]:.0f}", f"{days * DAY[2] / 60:.1f}"])
table(["Акт, ч", "Суток", "Ночей", "Часов ночи"], rows)
print(f"Доля ночи: {DAY[2]}/{day_len} = {DAY[2] / day_len:.0%} (с сумерками и рассветом — {(DAY[1] + DAY[2] + DAY[3]) / day_len:.0%}). "
      "Terraria: цикл 24 мин, день 15 и ночь 9 — ночь 37,5 %. "
      "Ночь 6 мин — это 2 160 тайлов бега или полный переход через полэкватора; «пересидеть» её в доме — 6 минут без дела, 30–45 раз за акт.\n")
print("Арифметика документа: 10 + 12 + 12 = 34 ч, 12 + 15 + 15 = 42 ч → соло 34–42, не 35–42; раздел 3 говорит «акт 12–15 ч», таблица — «акт I 10–12».\n")

# 3. Экран и тайл ------------------------------------------------------------------------
print("## 3. Тайл на экране\n")
rows = []
for w, hgt, name in ((1920, 1080, "1080p"), (2560, 1440, "1440p"), (3840, 2160, "4K")):
    px = w / SCREEN_W
    rows.append([name, f"{px:.0f}", f"×{px / 64:.2f}", f"×{px / 128:.2f}", f"{px * 1.5:.0f}", f"{hgt / px:.1f}"])
table(["Экран", "px на тайл при 40 тайлах в ширину", "от исходника 64 px", "от исходника 128 px",
       "Рост персонажа (1,5 тайла), px", "Тайлов в высоту"], rows)
rows = []
for z in (0.5, 0.75, 1.0):
    px = 64 * z
    rows.append([f"×{z}", f"{px:.0f}", f"{1920 / px:.0f} × {1080 / px:.1f}", f"{px * 1.5:.0f}", f"{px * 0.8:.0f}"])
table(["Зум (от 64 px)", "px/тайл при 1080p", "Видно тайлов", "Рост персонажа, px", "Диаметр коллизии 0,8 т, px"], rows)
rows = [
    ["Terraria (2011)", "16 px (пиксель)", "120 × 67,5", "≈ 42"],
    ["Factorio (2016)", "32 px (исходник 64 — «hr»)", "60 × 33,75", "≈ 1,5–2 тайла ≈ 50–64"],
    ["Stardew Valley (2016)", "64 px (исходник 16 ×4)", "30 × 16,9", "128 (спрайт 16 × 32, ×4)"],
    ["Orpheus (документ)", "48 px (исходник 64 ×0,75)", "40 × 22,5", "72"],
]
table(["Игра", "Тайл на экране при 1080p", "Видно тайлов", "Рост персонажа на экране, px"], rows)

# 4. Срез: бюджет двух часов -------------------------------------------------------------------
print("## 4. Срез: что нужно успеть за 2 часа троим с нуля (прикидка минут при знании игры и без смертей)\n")
budget = [
    ("Осмотреться, первые инструменты (дерево → камень)", 10),
    ("Ресурсы на дом с двумя комнатами (стены, пол, двери, мебель)", 15),
    ("Построить дом, дождаться первого спутника", 10),
    ("Найти горы/пещеры, медь → медные инструменты и оружие", 20),
    ("Железо → железный ярус (оружие, броня)", 15),
    ("Условие второго спутника", 8),
    ("Дойти до данжа и зачистить (условие зачистки)", 18),
    ("Босс акта I: вызов, бой с фазами", 12),
    ("Вложить 5 очков, сменить набор у первого спутника, проверить второй набор", 7),
]
total = sum(m for _, m in budget)
table(["Шаг", "Мин"], [[s, m] for s, m in budget] + [["**Итого**", f"**{total}**"], ["×1,5 для новичков (поиск, смерти, тупики)", f"{total * 1.5:.0f}"]])

# 5. Очки в срезе ------------------------------------------------------------------------------
print("## 5. Пять очков из двух источников\n")
print("В срезе опыт дают только зачистка данжа и босс (обход планеты — вне среза). Потолок 5. "
      "Значит либо данж = 2 уровня и босс = 3 (или 1 + 4), либо третий источник. Сейчас в документе это не сказано, "
      "и критерий «вложили 5 очков» невыполним по тексту.\n")

# 6. Сеть и чанки ------------------------------------------------------------------------------
print("## 6. Чанки вокруг игрока\n")
loaded = 6 * 4  # 6×4 чанков = 192 × 128 тайлов — экран 40×22,5 плюс кольцо
print(f"Экран 40 × 22,5 тайла накрывает 2–3 × 1–2 чанка; с кольцом подгрузки — {loaded} чанка = {f(loaded * CHUNK * CHUNK, 0)} тайлов "
      f"≈ {loaded * CHUNK * CHUNK * 8 / 1e3:.0f} КБ при 8 Б на тайл на игрока; на 8 игроков в разных местах — {8 * loaded} чанка, "
      f"{8 * loaded * CHUNK * CHUNK / 1e6:.2f} M тайлов — {100 * 8 * loaded / (4096 // CHUNK) ** 2:.1f} % мира.")
print(f"Чанк пробегается за {CHUNK / RUN:.1f} с; при беге по прямой клиенту нужно ≈ 4 новых чанка каждые {CHUNK / RUN:.1f} с "
      f"≈ {4 * CHUNK * CHUNK * 8 / (CHUNK / RUN) / 1e3:.0f} КБ/с без сжатия — для сети мелочь.\n")

print("## 7. Сохранение\n")
print(f"Полный снимок 4096² при 8 Б на тайл — {4096**2 * 8 / 1e6:.0f} МБ; при 1 Б пола + 2 Б объекта + 1 Б состояния — "
      f"{4096**2 * 4 / 1e6:.0f} МБ до сжатия. Если хранить только отличия от генерации по зерну (игроки правят, "
      f"скажем, по 200 000 тайлов каждый): 8 × 200 000 × 8 Б = {8 * 200000 * 8 / 1e6:.1f} МБ. Автосохранение полного снимка "
      "каждые N минут — запись 70–130 МБ; дельты — мегабайты.")
