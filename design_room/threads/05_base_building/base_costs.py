# 8. Сон и кровати ---------------------------------------------------------------------------
print("## 8. Сон x6 и кровати на компанию\n")
dusk_night = 7.0
print(f"Сумерки и ночь — {f(dusk_night, 0)} мин, при x6 — {f(dusk_night / 6)} мин; экономия {f(dusk_night - dusk_night / 6)} мин за ночь. "
      f"Срез — 3 ч = 9 суток без сна: экономия до {f(9 * (dusk_night - dusk_night / 6), 0)} мин, около четверти бюджета, "
      f"если сон не блокируется (`05` 7.3 требует, чтобы в 20 тайлах от спящих не было врагов, а `05` 6.3 ведёт врагов к стенам ночью).\n")
rows = []
for players, comps in ((1, 1), (3, 2), (4, 6), (8, 6), (8, 13)):
    beds = players + comps
    now = comps + math.ceil(players / 3)
    fix = comps + max(0, math.ceil((players - 2 * comps) / 3))
    rows.append([players, comps, beds, now, house(now, beds)["units"], fix, house(fix, beds)["units"]])
table(["Игроков", "Спутников", "Кроватей (сон — каждому своя)", "Комнат по 3.3 как есть", "ед.",
       "Комнат, если кровать игрока не занимает комнату", "ед."], rows)
print("Как есть, первая же кровать игрока в единственной комнате делает её занятой — Каллиопа не приходит.\n")
