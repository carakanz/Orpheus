    trees = math.ceil(wood / A.wood_per_tree)
    grass = math.ceil(fiber / A.fiber_per_grass)
    t = stone * 1.0 + trees * 1.5 + grass * 1.0
    return [name, stone, wood, fiber, trees, f(t, 0) + " с", f(t * A.walk / 60) + " мин"]


