def lean_to(a, b, gate_cost=6, gate_tiles=1):
    """Двор a тайлов вдоль стены дома и b вглубь; стена дома - северная граница."""
    fence = 2 * b + a + 2 - gate_tiles
    return a * b, fence, fence + gate_cost


def ring(w, h, gate_cost=6, gate_tiles=1):
    """Кольцо забора в одном тайле от дома w x h (снаружи): ограда (w + 4) x (h + 4)."""
    fence = 2 * ((w + 4) + (h + 4)) - 4 - gate_tiles
    return (w + 2) * (h + 2) - w * h, fence, fence + gate_cost


