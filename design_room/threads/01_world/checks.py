#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Арифметика разбора 01_world (Критик 01, 28.10): кольца и опасность по направлениям, уровни акта I,
хранители и алтарь, роща вокруг закрытого портала (120 или 200), свет и видимость ночью,
накопители обхода, защищённые круги и котловина, время генерации по бенчу Критика 00,
расстояние до поясов (из модели worldgen_model.py).

Запуск: python C:\\Users\\carak\\source\\Orpheus\\design_room\\threads\\01_world\\checks.py
"""
import math, os, sys
import numpy as np

sys.stdout.reconfigure(encoding='utf-8')
P = print
W = 4096; R = W // 2


def wrap(v):
    return (v + R) % W - R


# ------------------------------------------------------------ 1. кольца
P('# Проверки разбора 01_world\n')
P('## 1. Кольца опасности: площадь, ожидаемая сила врага, профиль по направлениям (4096²)\n')
rings = [(0, 256), (256, 1024), (1024, 2048), (2048, 1e9)]
mix = [(1, 0, 0), (1, 0, 0), (0.7, 0.3, 0), (0.55, 0.30, 0.15)]   # доли ярусов 1/2/3 (01, раздел 3)
hp = (1.0, 1.5, 2.2); dm = (1.0, 1.25, 1.5)                          # множители ярусов (01 → принято 02, 8.7)
P('| Кольцо | Доля площади | Здоровье врага, × | Удар, × | «Угроза» = здоровье × удар, × |')
P('|---|---|---|---|---|')
area = []
for i, (a, b) in enumerate(rings):
    b2 = min(b, R)
    s = math.pi * (b2 ** 2 - a ** 2) / W ** 2 if a < R else 0
    if b > R:
        s = 1 - math.pi * a ** 2 / W ** 2
    area.append(s)
    eh = sum(m * x for m, x in zip(mix[i], hp)); ed = sum(m * x for m, x in zip(mix[i], dm))
    P(f'| {i} | {100 * s:.1f} % | {eh:.2f} | {ed:.3f} | {eh * ed:.2f} |')
P('\nДля сравнения: переход акта I → II — здоровье ×3,4, удар ×2,5 (`00`, 5.2), «угроза» ×8,6; ночь — ×1,25 и ×1,25, «угроза» ×1,56.\n')

P('Профиль «ушёл прямо от Очага и иду дальше» — какое наибольшее удаление и сколько пути в каждом кольце за полный проход (W тайлов по направлению):\n')
P('| Направление | Наибольшее d | Доля пути в кольце 0 / 1 / 2 / 3 | Что встречает на пике |')
P('|---|---|---|---|')
for name, ang in (('восток (экватор)', 0.0), ('22,5°', 22.5), ('северо-восток (диагональ)', 45.0)):
    th = math.radians(ang)
    L = W if ang in (0.0,) else (W * math.sqrt(2) if ang == 45.0 else W / math.cos(th))
    s = np.linspace(0, L, 20001)
    x = wrap(s * math.cos(th)); y = wrap(s * math.sin(th))
    d = np.sqrt(x * x + y * y)
    cnt = [np.mean((d >= a) & (d < b)) for a, b in rings]
    peak = 'жаркий пояс (X = ±R)' if ang == 0 else ('Перекрёсток и Изнанка' if ang == 45 else 'оба пояса поочерёдно')
    P(f'| {name} | {d.max():.0f} | ' + ' / '.join(f'{100 * c:.0f} %' for c in cnt) + f' | {peak} |')
P('\nВывод: по любому лучу опасность растёт одинаково до d = 2048 (кольца — окружности); различие направлений только в том, что на конце: '
  'по осям — пояс (восток = запад, север = юг: это одна и та же полоса), по диагоналям — Изнанка. Кольцо 2 — 58,9 % площади при «угрозе» ×1,24 против ×1,00 — градиента внутри акта почти нет.\n')
# непрерывная доля ярусов
P('Предложение — доля ярусов как функция d (вместо ступенек колец): ярус 2 — 0 % при d = 1024 → 45 % при d = 2048; ярус 3 — 0 % при d = 1700 → 30 % при d = 2896:\n')
P('| d | ярус 1 / 2 / 3 | «угроза», × |')
P('|---|---|---|')
for dd in (1024, 1400, 1700, 2048, 2400, 2896):
    p2 = min(max((dd - 1024) / 1024, 0), 1) * 0.45
    p3 = min(max((dd - 1700) / (2896 - 1700), 0), 1) * 0.30
    p1 = 1 - p2 - p3
    eh = p1 + 1.5 * p2 + 2.2 * p3; ed = p1 + 1.25 * p2 + 1.5 * p3
    P(f'| {dd} | {100 * p1:.0f} / {100 * p2:.0f} / {100 * p3:.0f} % | {eh * ed:.2f} |')
P('')

# ------------------------------------------------------------ 2. уровни
P('## 2. Уровни акта I (потолок 10, `00`)\n')
P('| Источник | 01 (раздел 4) | 04 (раздел 8) | 8192² по тексту 01 |')
P('|---|---|---|---|')
P('| Зачистки данжей акта I | 7 × 1 | 7 × 1 | 10 × 1 (5 разбойничьих, 2 Лабиринта, Храм, Гнездо, Грот) |')
P('| Босс акта (Цербер) | 3 | 3 | 3 |')
P('| Набег отбит, Изнанка, Обход, Все биомы акта I | — (обход и Изнанка названы достижениями без чисел) | 1 + 1 + 1 + 1 | 4 |')
P('| **Итого / запас над потолком 10** | **10 / 0** | **14 / 4** | **17 / 7** |')
P('\nС запасом 0 (как в 01) потолок 10 впервые достигается в момент победы над боссом акта — то есть в акте I его не бывает; '
  'перед боссом у персонажа не больше 7. На 8192² запас 7 — почти половина данжей не нужна.\n')

# ------------------------------------------------------------ 3. хранители и алтарь
P('## 3. Хранители: время «чистого урона» (без уворотов), акт I\n')
base = 35; dps = 16                                   # 02: здоровье обычного врага акта I; 04: урон в секунду персонажа акта I
P('Здоровье хранителя = 35 × множитель яруса (01: ×8 / ×15 / ×25); урон в секунду персонажа — 16 (04, раздел 6.1).\n')
P('| Ярус | Здоровье соло | 1 игрок | 4 игрока без масштаба | 8 без масштаба | 8 с масштабом 02 ×(1 + 0,5(N−1)) | 8, «отголосок» ×0,6 с масштабом |')
P('|---|---|---|---|---|---|---|')
for t, mul in ((1, 8), (2, 15), (3, 25)):
    hpg = base * mul
    f = lambda n, sc=False, e=1.0: hpg * e * ((1 + 0.5 * (n - 1)) if sc else 1) / (dps * n)
    P(f'| {t} | {hpg} | {f(1):.0f} с | {f(4):.1f} с | {f(8):.1f} с | {f(8, True):.1f} с | {f(8, True, 0.6):.1f} с |')
P('\nВывод: без масштабирования восьмеро снимают хранителя яруса 1 за 2,2 с — 02 право. С формулой 02 бой с хранителем — 10–60 с при любом N.\n')
P('Алтарь как написан (касание = уровень): опоздавший в акте I получает до 7 уровней за 7 касаний — 7 переходов по ~800 тайлов, '
  f'≈ {7 * 800 / 6 / 60 * 1.5:.0f} мин бега с обходом ×1,5 — и ни одного боя.\n')

# ------------------------------------------------------------ 4. роща вокруг закрытого портала
P('## 4. Волшебный лес вокруг закрытого портала: 120 или 200\n')
share = 0.35   # лес + луга + джунгли акта II среди проходимых тайлов вне океана (13+11+4 из ≈ 80)
P(f'Порталы открываются равномерно по проходимой площади (01, раздел 9); доля преображаемых тайлов (лес, луга, джунгли акта II) около {share:.2f}. Очаги дают 4 % (модель: 3,6 %), потолок — 10 %.\n')
P('| Радиус | Тайлов на портал | % мира на портал | 10–12 порталов (как считал 01) | 40 порталов (минимум 4 круга по 04) | 60 порталов (два поражения) | Портал, на котором упираемся в потолок 10 % |')
P('|---|---|---|---|---|---|---|')
for r in (120, 200):
    per = math.pi * r * r * share
    pc = 100 * per / W ** 2
    cap_n = math.ceil((10 - 4) / pc)
    P(f'| {r} | {per:,.0f} | {pc:.2f} | {4 + 10 * pc:.1f}–{4 + 12 * pc:.1f} % | {min(10, 4 + 40 * pc):.1f} % | {min(10, 4 + 60 * pc):.1f} % | {cap_n}-й |'.replace(',', ' '))
r_need = math.sqrt(0.04 * W * W / 40 / share / math.pi)
P(f'\nЧтобы 40 порталов дали те же 4 %, что 01 закладывал на 10–12, нужен радиус ≈ {r_need:.0f}. Таблица долей акта II (волшебный лес 8 %) сходится с радиусом 120 при 40–50 порталах; при 200 доля упирается в потолок 10 % уже во втором круге.\n')

# ------------------------------------------------------------ 5. свет
P('## 5. Свет ночью: где существа не рисуются (L < 0,2) и сколько дают факелы\n')
night = 0.3
rows = [('луга, болота, пустыня, город', night), ('лес (k 0,85)', night * 0.85), ('джунгли (k 0,7)', night * 0.7),
        ('лес в дождь (×0,8)', night * 0.85 * 0.8), ('джунгли в дождь', night * 0.7 * 0.8), ('тундра', 0.35), ('ледник', 0.45),
        ('Предвратие', 0.2), ('пещеры (всегда)', 0.15), ('отдельный данж', 0.1)]
P('| Где, ночь | L фона | Враг без факела |')
P('|---|---|---|')
for n, l in rows:
    P(f'| {n} | {l:.3f} | {"не рисуется" if l < 0.2 else "виден"} |')
P('\nСцена раздела 6 («за кругом факела в лесу — силуэты, движущееся не видно») при фоне ночи 0,3 не выполняется: в лесу L = 0,255 ≥ 0,2. '
  'Темно только в пещерах, отдельных данжах и в джунглях под дождём.\n')
for nm, r0, r1 in (('факел', 3, 6), ('костёр', 4, 8)):
    for thr, what in ((0.5, 'запрет появления (только построенный свет)'), (0.7, 'тени не входят (предложение 01, принято 02) — с фоном ночи 0,3')):
        part = thr - (0.3 if thr == 0.7 else 0.0)
        dd = r1 - part * (r1 - r0)
        P(f'- {nm} {r0}/{r1}: {what} — до {dd:.1f} тайлов, круг {math.pi * dd * dd:.0f} тайлов.')
P('\nТень — быстрый ближний (укус при касании): персонаж в круге своего факела радиусом 4,8 недосягаем для теней вообще. '
  'Факел стоит 1 древесину и 1 смолу и ставится клавишей T (02, 1.1).\n')

# ------------------------------------------------------------ 6. накопители обхода
P('## 6. Накопители обхода: «Экватор» без обхода\n')
U = 0.0; walked = 0
for trip in range(5):
    U += 1000; walked += 1000          # 1000 тайлов на восток от базы
    # возврат на базу: по 01 «телепорт U не меняет»
P(f'Правило 01: пять вылазок «1000 тайлов на восток от базы → возврат на базу» дают U_x = {U:.0f} ≥ 4096 — «Экватор» (по 04 — +1 уровень), '
  f'хотя персонаж ни разу не был дальше 1000 от базы и не видел 76 % долгот.')
U2 = 0.0
for trip in range(5):
    U2 += 1000
    U2 += wrap(0 - 1000)               # предложение: телепорт добавляет свёрнутую дельту
P(f'Если телепорт добавляет к U свёрнутую дельту перемещения, те же пять вылазок дают U_x = {U2:.0f}. '
  'Вариант без дыр: маска 512 долгот (по ячейке 8 тайлов) на персонаже, «Экватор» — все 512 пройдены пешком; 64 байта на персонажа.\n')

# ------------------------------------------------------------ 7. защищённые круги
P('## 7. Защищённые круги 48 и котловина\n')
room = dict(stone=30, wood=26, resin=1, fiber=5)
kot = 0.12 * W * W
P(f'Самая дешёвая годная комната по 05 (3 × 3 внутри: 15 стен × 2 камня, дверь 6, пол 9, факел 1 + 1 смола, кровать 10 + 5 волокна): '
  f'{sum(room.values())} единиц ресурсов. Круг 48 — {math.pi * 48 * 48:.0f} тайлов.')
for sp in (96, 83):
    n = kot / (sp * sp)
    P(f'- Котловина {kot / 1e6:.2f} млн тайлов; комнаты сеткой через {sp} тайлов: {n:.0f} комнат = {n * 62:,.0f} ресурсов — '
      f'океан теряет {100 * min(1, math.pi * 48 * 48 / (sp * sp)):.0f} % площади.'.replace(',', ' '))
P(f'- Если защищают только занятые комнаты (спутник или назначенная кровать; 13 спутников + 8 игроков): ≤ 21 круг = '
  f'{21 * math.pi * 48 * 48 / 1e3:.0f} тыс. тайлов, {100 * 21 * math.pi * 48 * 48 / W / W:.1f} % мира.\n')

# ------------------------------------------------------------ 8. время генерации
P('## 8. Время генерации 4096² по бенчу Критика 00 (C:\\Users\\carak\\source\\Orpheus\\design_room\\threads\\00_vision\\noise_bench\\result.md)\n')
s1, sN = 57.9e6, 183.4e6           # выборок шума в секунду: 1 поток / 16 потоков
bfs = 0.166                        # заливка 4096² тайлов, 1 поток
M = W // 8
stages = [
    ('2. поля h, m, c на макрокарте 512²', (4 + 3 + 3) * M * M / s1),
    ('6. разбиение и слияние (компоненты на макрокарте, диаметры)', 0.3),
    ('4. вода: озёра, 25–40 рек спуском по h', 0.1),
    ('11. связность по тайлам (3 заливки с прорубкой перевалов)', 3 * bfs),
    ('12. чанки: деталь границ 2 октавы на тайл', 2 * W * W / s1),
    ('12. чанки: объекты — ~6 хэшей на тайл (≈ 400 М/с)', 6 * W * W / 4e8),
    ('13. проверки: заливка, доли, POI, хэш', bfs + 0.1),
]
tot = 0
P('| Этап | Секунд, 1 поток |')
P('|---|---|')
for n, t in stages:
    tot += t
    P(f'| {n} | {t:.2f} |')
P(f'| **Итого** | **{tot:.1f}** |')
P(f'\nОдин проход ≈ {tot:.1f} с в одном потоке; три попытки зерна (провал гарантий) — {3 * tot:.0f} с: лимит 30 с выдержан с запасом, '
  f'даже если целочисленный шум вдвое медленнее плавающего. 8192² — ×4: ≈ {4 * tot:.0f} с, с тремя попытками {12 * tot:.0f} с ≤ 90. '
  f'Память 8192²: тайлы 4 Б × 67 М = 268 МБ + очередь заливки int32 268 МБ — у хоста с игрой на той же машине это заметно (битовая маска и очередь по чанкам — ≈ 300 МБ).\n')

# ------------------------------------------------------------ 9. до поясов (модель)
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
try:
    import worldgen_model as wm
    P('## 9. Ближайшая точка каждого пояса от Очага (модель, 4096², 30 зёрен, без форпостов)\n')
    acc = {k: [] for k in (wm.JUNGLE, wm.DESERT, wm.LAVA, wm.TUNDRA, wm.GLACIER)}
    for s in range(1, 31):
        coords, h, m, c, shH, shC = wm.fields(4096, s)
        X, d, dH, dC, dA = wm.geometry(4096, coords, shH, shC)
        T = wm.calibrate(h, m, c, dH < 300, dC < 250, 1.0, dH)
        b, hot, cold = wm.classify(4096, h, m, c, dH, dC, dA, T, True)
        for k in acc:
            acc[k].append(wm.near_biome_min_d(b, d, k))
    P('| Биом | Ближайшая точка от Очага, тайлов (мин–медиана–макс) | Минут бега по прямой (медиана) |')
    P('|---|---|---|')
    for k, v in acc.items():
        v = np.array(v)
        P(f'| {wm.NAMES[k]} | {v.min():.0f} – {np.median(v):.0f} – {v.max():.0f} | {np.median(v) / 360:.1f} |')
    P('\nБез форпостов ближайший пояс — в 4–5 минутах бега по прямой (6–7 с обходом ×1,5). С форпостами «Все биомы акта I» (подвиг 04, +1 уровень) закрывается за один круг в кольце 1, не выходя к поясам.')
except Exception as e:  # модель не обязательна для остальных проверок
    P(f'(раздел 9 пропущен: {e})')

# ------------------------------------------------------------ 10. ширина поясов под таблицу и озёра в котловине
P('\n## 10. Ширина поясов под долю 28 % и озёра, которые забирает котловина\n')
ratio = 0.82   # доля биомов поясов в площади поясов после гор и пещер (модель: 20,6 / 25,1)
lo, hi = 0.0, 0.5
for _ in range(60):
    x = (lo + hi) / 2
    union = x + 0.8333 * x - 0.8333 * x * x
    if union * ratio < 0.28:
        lo = x
    else:
        hi = x
P(f'Чтобы пять биомов поясов заняли 28 % при соотношении ширин 600 : 500, нужны пояса ≈ {x * W:.0f} и {0.8333 * x * W:.0f} тайлов '
  f'(сейчас 600 и 500 — объединение 25,1 %, биомов поясов 20,6 %).')
try:
    for s in (1, 2, 3):
        r = wm.one_world(4096, s, calib=True, do_regions=False, do_dungeons=False)
        b, d, kot = r['b'], r['d'], r['kotmask']
        lake = b == wm.LAKE
        band = (d >= 1200) & (d <= 2047)
        L = np.argwhere(lake & ~kot)
        C = np.argwhere(np.isin(b, [wm.CAVE, wm.MOUNT]) & band & ~kot)
        Mm = b.shape[0]
        dmin = []
        for (y, xx) in C[::max(1, len(C) // 1500)]:
            dy = np.abs(L[:, 0] - y); dy = np.minimum(dy, Mm - dy)
            dx = np.abs(L[:, 1] - xx); dx = np.minimum(dx, Mm - dx)
            dmin.append(np.sqrt(dx * dx + dy * dy).min() * 8)
        P(f'- зерно {s}: котловина забрала {100 * (lake & kot).sum() / lake.sum():.0f} % озёр; от гор и пещер кольца 2 (1200–2047) '
          f'до ближайшего озера вне котловины — не меньше {min(dmin):.0f} тайлов')
except Exception as e:
    P(f'(озёра пропущены: {e})')
