def p_lost(rtt, sig_ind, sig_common=0.0, clock_sigma=3.0):
    owd = rtt / 2.0
    # интегрируем по фазе такта (равномерно), ошибке часов и общей составляющей (сетка по нормальному)
    phases = [TICK * (i + 0.5) / 40 for i in range(40)]
    zs = [(-3.0 + 6.0 * (k + 0.5) / 31) for k in range(31)]
    wz = [math.exp(-z * z / 2) for z in zs]
    sw = sum(wz)
    wz = [w / sw for w in wz]
    total = 0.0
    for ph in phases:
        deadline = WAIT + ph
        acc_e = 0.0
        for ze, we in zip(zs, wz):
            e = ze * clock_sigma
            if sig_common > 0:
                acc_c = 0.0
                for zc, wc in zip(zs, wz):
                    c = zc * sig_common
                    pr = 1.0
                    for j in range(4):
                        pr *= q(deadline - (j * FRAME + owd + e + c), sig_ind)
                    acc_c += wc * pr
                acc_e += we * acc_c
            else:
                pr = 1.0
                for j in range(4):
                    pr *= q(deadline - (j * FRAME + owd + e), sig_ind)
                acc_e += we * pr
        total += acc_e
    return total / len(phases)


