def ru(x, nd=0):
    s = f"{x:.{nd}f}"
    return s.replace(".", ",").replace("-", "−")


def q(x, sigma):
    """P(N(0, sigma) > x)."""
    if sigma <= 0:
        return 1.0 if x < 0 else 0.0
    return 0.5 * math.erfc(x / (sigma * math.sqrt(2.0)))


