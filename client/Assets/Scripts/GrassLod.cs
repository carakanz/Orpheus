    /// <summary>
    /// C-046: чистая математика LOD растительности (без UnityEngine — linked в тесты).
    /// Слово Автора 21.11 «при отдалении не пропадает графика»: на обзоре 40/64/96 тайлов
    /// показана ОДНА И ТА ЖЕ растительность — пучки травы и куртины цветов МЕЛЬЧЕ вместе
    /// с кадром, но НЕ РЕЖЕ. Прежняя формула <c>Clamp01((viewTiles − 64)/32) · 0,65</c>
    /// прятала до 65 % пучков на обзоре 96 (шейдер схлопывал квад в точку —
    /// <c>Grass.shader</c>, <c>_OrphGrass.x</c>), и поле на обзоре «лысело».
    /// Число держит тест <c>C046GrassLodTests</c>: любой ненулевой возврат красит тест.
    /// </summary>
    public static class GrassLod
    {
        /// <summary>
        /// Доля пучков травы и куртин цветов, скрытых на обзоре в <paramref name="viewTiles"/>
        /// тайлов (0..1). 0 — ничего не скрыто (правило Автора «мельче, но не реже»).
        /// Если для кадра понадобится LOD, его делают ДРУГИМ способом (дешевле квад, краска,
        /// отсечение по чанкам), а не прореживанием: просадка по кадрам меряется на обзоре 96
        /// и фиксируется в карточке C-046.
        /// </summary>
        public static float HideFraction(float viewTiles) => 0f;
    }
}
