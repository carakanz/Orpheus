using Orpheus.Net.Protocol;

namespace Orpheus.Net
{
    /// <summary>
    /// Модуль сети (docs/07, 2.10): протокол, снимки, часы, <c>ITransport</c> (LiteNetLib, связь в памяти, имитатор).
    /// </summary>
    public static class NetModule
    {
        /// <summary>Версия протокола: растёт с каждым несовместимым изменением схемы сообщений.</summary>
        public const int ProtocolVersion = 13; // 2 — хэш генерации во «входе принят» (0-017); 3 — токен хозяина во входе, «Открыть для друзей», «мир закрывается» (0-024); 4 — эпоха часов в снимке и дельте, Ping/Pong (0-025); 5 — мир по сети: чанк, пачка правок, центр окна, запрос чанка (0-026); 6 — уворот в своём состоянии снимка, «замах начат» (13) и «удар решён» (14) (0-029); 7 — запрос правки (20) и ответ на неё (21) (0-028); 8 — опережение L в вводе (0…24), отчёт «запас прихода кадров» и D_p в своём состоянии снимка, D_p получателя в «замах начат» (0-033); 9 — отказ входа «имя занято» (0-035); 10 — пауза: запрос (22) и состояние (23) (0-036); 11 — бой: здоровье/масса/отбрасывание в своём состоянии, доля здоровья сущности в снимке (7 бит, маска дельты), урон в «ударе решён», смерть (24) и возрождение (25) (1-001); 12 — кадр ввода: угол прицела и ячейка быстрой панели (InputFrame 6 байт — журнал формата 2, WireFrame 7 байт, InputMessage 42 байта) (1-002); 13 — сумка (26): предмет в руках сущности в снимке (8 бит, маска дельты 4 бита) и сумка владельцу при входе и изменении (1-002)

        /// <summary>
        /// Версия сборки, которую сверяет вход (2.10: «клиент и сервер разных сборок не соединяются»). Пока номера
        /// сборки из CI нет — 0.0.<see cref="ProtocolVersion"/>.
        /// </summary>
        public static readonly NetVersion Version = new NetVersion(0, 0, ProtocolVersion);
    }
}
